// Generate contracts/component-contracts.json — tier 3 of the Flutter roadmap
// (docs/architecture-flutter.md §5): the Flutter port's acceptance list,
// distilled from the docs' component-meta.json plus the hand-curated
// portability classification in contracts/flutter-portability.mjs.
//
//   pnpm gen        (from the repo root — runs every generator in order)
//
// Runs after gen:meta because it reads its committed output rather than
// running vue-component-meta a second time: one checker run, one source of
// truth, and every guard gen-meta already enforces (no `any`, no blank
// components) is inherited for free.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import {
  WEB_ONLY_COMPONENTS,
  WEB_ONLY_PROP_PATTERN,
  WEB_ONLY_PROP_PATTERN_REASON,
  WEB_ONLY_PROPS,
} from '../contracts/flutter-portability.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

const meta = JSON.parse(
  readFileSync(
    join(root, 'apps', 'docs', 'app', 'generated', 'component-meta.json'),
    'utf8'
  )
)

// ── Staleness guards ────────────────────────────────────────────────────
// The classification is hand-written, so the failure mode is the same one
// gen-llms guards against: entries that outlive the thing they classify. A
// name that no longer exists in the meta is a curation bug, not a no-op.
const dead = []
for (const name of Object.keys(WEB_ONLY_COMPONENTS)) {
  if (!meta[name]) dead.push(`WEB_ONLY_COMPONENTS.${name}`)
}
for (const [name, props] of Object.entries(WEB_ONLY_PROPS)) {
  if (!meta[name]) {
    dead.push(`WEB_ONLY_PROPS.${name}`)
    continue
  }
  if (WEB_ONLY_COMPONENTS[name]) {
    dead.push(`WEB_ONLY_PROPS.${name} (component is already web-only)`)
    continue
  }
  const have = new Set(meta[name].props.map((p) => p.name))
  for (const prop of Object.keys(props)) {
    if (!have.has(prop)) dead.push(`WEB_ONLY_PROPS.${name}.${prop}`)
  }
}
if (dead.length) {
  console.error(
    `gen-flutter-contracts: ${dead.length} stale ${dead.length === 1 ? 'entry' : 'entries'} in contracts/flutter-portability.mjs:`
  )
  for (const d of dead) console.error(`  ${d}`)
  process.exit(1)
}

// ── Design-type vocabulary ──────────────────────────────────────────────
// Contract prop types are TypeScript strings and freely name the shared
// design unions (KunUIColor, …). Enumerate them so the file stands alone.
// Read as text, like gen-llms reads componentNames.ts: types.ts is pure
// type-level, so there is nothing to import at runtime.
const typesSrc = readFileSync(
  join(root, 'packages', 'ui-core', 'src', 'types.ts'),
  'utf8'
)
const vocabulary = {}
for (const name of ['KunUIVariant', 'KunUIColor', 'KunUISize', 'KunUIRounded']) {
  const m = typesSrc.match(new RegExp(`export type ${name} =([^\\n]*(?:\\n\\s*\\|[^\\n]*)*)`))
  const members = m ? [...m[1].matchAll(/'([^']+)'/g)].map((x) => x[1]) : []
  if (members.length < 2) {
    console.error(
      `gen-flutter-contracts: could not read the ${name} union from packages/ui-core/src/types.ts — the parser needs updating.`
    )
    process.exit(1)
  }
  vocabulary[name] = members
}

// ── Emit ────────────────────────────────────────────────────────────────
const components = {}
for (const name of Object.keys(meta).sort()) {
  if (WEB_ONLY_COMPONENTS[name]) {
    components[name] = { status: 'web-only', reason: WEB_ONLY_COMPONENTS[name] }
    continue
  }
  const { props, events, slots } = meta[name]
  const webOnlyProps = {}
  const crossing = []
  for (const p of props) {
    if (WEB_ONLY_PROP_PATTERN.test(p.name)) {
      webOnlyProps[p.name] = WEB_ONLY_PROP_PATTERN_REASON
    } else if (WEB_ONLY_PROPS[name]?.[p.name]) {
      webOnlyProps[p.name] = WEB_ONLY_PROPS[name][p.name]
    } else {
      crossing.push(p)
    }
  }
  components[name] = {
    status: 'portable',
    props: crossing,
    webOnlyProps,
    events,
    slots,
  }
}

const counts = Object.values(components).reduce(
  (acc, c) => {
    acc[c.status === 'portable' ? 'portable' : 'webOnly']++
    return acc
  },
  { portable: 0, webOnly: 0 }
)

const out = {
  $comment:
    'AUTO-GENERATED by scripts/gen-flutter-contracts.mjs — do not edit. The Flutter port’s acceptance list (tier 3, docs/architecture-flutter.md §5); format and parity semantics in contracts/README.md.',
  vocabulary,
  components,
}

const dir = join(root, 'contracts')
mkdirSync(dir, { recursive: true })
writeFileSync(
  join(dir, 'component-contracts.json'),
  `${JSON.stringify(out, null, 2)}\n`
)
console.log(
  `wrote contracts/component-contracts.json — ${counts.portable} portable, ${counts.webOnly} web-only`
)
