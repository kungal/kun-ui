// Extract KunUI's own Tailwind scale names from @kungal/ui-tokens so `cn()` can
// teach tailwind-merge about them. Output: src/twScales.generated.ts (committed).
//
//   pnpm gen        (from the repo root — runs every generator in order)
//
// tailwind-merge ships Tailwind's default scales and nothing else, so a class
// it cannot parse is passed through untouched and never resolved against a
// conflicting one. Everything below is a name Tailwind v4 mints from this
// repo's `@theme` / `@utility` blocks, i.e. exactly the set tailwind-merge
// cannot know about. Generated rather than hand-listed because a drifted list
// fails silently: the class merges, nobody sees an error, and two conflicting
// utilities ship together with CSS source order deciding the winner.

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join, relative } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..', '..', '..')
const tokensFile = join(root, 'packages', 'ui-tokens', 'src', 'tokens.css')
const outFile = join(here, '..', 'src', 'twScales.generated.ts')

const css = readFileSync(tokensFile, 'utf8')

// `--radius-kun-lg: …` inside @theme → the utility `rounded-kun-lg`. The value
// half of the name is what tailwind-merge stores, so strip the namespace only.
const themeScale = (namespace) => {
  const found = new Set()
  const re = new RegExp(`^\\s*--${namespace}-([A-Za-z0-9][A-Za-z0-9-]*)\\s*:`, 'gm')
  for (const m of css.matchAll(re)) found.add(m[1])
  return [...found].sort()
}

// `@utility z-kun-modal { … }` — a hand-written utility, so the whole class
// name is in the source and the prefix has to come back off.
const utilityScale = (prefix) => {
  const found = new Set()
  const re = new RegExp(`^@utility\\s+${prefix}-([A-Za-z0-9][A-Za-z0-9-]*)\\s*\\{`, 'gm')
  for (const m of css.matchAll(re)) found.add(m[1])
  return [...found].sort()
}

const scales = {
  radius: themeScale('radius'),
  shadow: themeScale('shadow'),
  ease: themeScale('ease'),
  animate: themeScale('animate'),
  z: utilityScale('z'),
  duration: utilityScale('duration'),
}

const empty = Object.entries(scales).filter(([, v]) => v.length === 0)
if (empty.length) {
  console.error(
    `gen-tw-scales: no values found for ${empty.map(([k]) => k).join(', ')} in ${relative(root, tokensFile)} — the token file moved or its shape changed.`
  )
  process.exit(1)
}

const body = Object.entries(scales)
  .map(
    ([key, values]) =>
      `  ${key}: [${values.map((v) => `'${v}'`).join(', ')}],`
  )
  .join('\n')

writeFileSync(
  outFile,
  `// AUTO-GENERATED by scripts/gen-tw-scales.mjs from @kungal/ui-tokens — do not edit.
//
// The Tailwind scale names KunUI mints itself. \`cn()\` feeds them to
// tailwind-merge, which otherwise cannot parse them and silently keeps two
// conflicting classes.
export const KUN_TW_SCALES = {
${body}
} as const
`
)

const total = Object.values(scales).reduce((n, v) => n + v.length, 0)
console.log(
  `wrote twScales.generated.ts — ${total} names across ${Object.keys(scales).length} scales`
)
